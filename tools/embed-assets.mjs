#!/usr/bin/env node
/* tools/embed-assets.mjs
 * GitHub MCP push_files rejects binary files, so all PNG/OGG assets are
 * embedded as base64 data-URLs into client/js/sunny-data.js (UTF-8 text).
 * Re-run after changing anything under client/assets/:
 *   node tools/embed-assets.mjs
 */
import { readdirSync, statSync, readFileSync, writeFileSync } from 'fs';
import { join, relative, extname } from 'path';

const CLIENT = new URL('../client/', import.meta.url).pathname;
const OUT = join(CLIENT, 'js', 'sunny-data.js');
const MIME = { '.png': 'image/png', '.ogg': 'audio/ogg' };

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (MIME[extname(e)]) out.push(p);
  }
  return out;
}

const files = walk(join(CLIENT, 'assets')).sort();
const entries = files.map((p) => {
  const key = relative(CLIENT, p).replace(/\\/g, '/'); // e.g. assets/Human/IDLE/base_idle_strip9.png
  const b64 = readFileSync(p).toString('base64');
  return `  ${JSON.stringify(key)}: "data:${MIME[extname(p)]};base64,${b64}"`;
});

const js = `/* AUTO-GENERATED by tools/embed-assets.mjs — do not edit by hand.
 * All binary game assets as data-URLs (GitHub push_files can't carry binary).
 * Regenerate: node tools/embed-assets.mjs */
globalThis.SUNNY_DATA = {
${entries.join(',\n')}
};
`;
writeFileSync(OUT, js);
const kb = Math.round(Buffer.byteLength(js) / 1024);
console.log(`wrote ${OUT}: ${files.length} assets, ${kb} KB`);
